// Table export to Excel (spec docs/superpowers/specs/2026-11-28-table-export-design.md):
// one export any screen hands its rows to; the footer comes from the signed-in
// user and the clock.
import 'dart:convert';
import 'dart:io';

import 'package:archive/archive.dart';

import 'package:basa_capstone/core/models/export_table.dart';
import 'package:basa_capstone/core/models/messages.dart';
import 'package:basa_capstone/core/services/xlsx_cells.dart';
import 'package:basa_capstone/core/wiring/app_context.dart';
import 'package:basa_capstone/core/wiring/wire_shared.dart';
import 'package:basa_capstone/core/wiring/wire_tutor.dart';
import 'package:basa_capstone/viewmodels/viewmodel_exception.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:sqflite_common_ffi/sqflite_ffi.dart';

import '../helpers/offline_owner.dart';

final _now = DateTime(2026, 11, 28, 9, 14);
const _footer = 'Generated by Maria Santos (Coordinator) on 28 Nov 2026, 9:14 AM';

const _table = ExportTable(
  'Section roster',
  school: 'ZZ School',
  schoolYear: '2026-2027',
  filters: ['Grade 7, Rizal', 'Search: cruz'],
  columns: [ExportColumn('LRN'), ExportColumn('Name'), ExportColumn('Score', kind: ExportColumnKind.number)],
  rows: [
    ['012345678901', 'CRUZ, Ana', 8],
    ['999600000002', 'CRUZ, Ben', null],
  ],
);

void main() {
  late AppContext ctx;
  late TutorVms t;

  Future<void> signInAs(String role, {int? schoolId, String name = 'Maria Santos'}) async {
    await ctx.authVm.signOut();
    final id = '00000000-0000-0000-0000-0000000000${const {'coordinator': 'c1', 'admin': 'a1', 'tutor': 't1'}[role]}';
    await seedOfflineOwner(ctx.localDb, userId: id, email: '$role@t', role: role, schoolId: schoolId);
    await ctx.localDb.update('users', {'full_name': name}, where: 'id = ?', whereArgs: [id]);
    expect(await ctx.authVm.signInOffline(email: '$role@t', password: 'test-pw'), isNull);
  }

  setUpAll(() async {
    sqfliteFfiInit();
    databaseFactory = databaseFactoryFfi;
    ctx = await AppContext.open(dataDir: Directory.systemTemp.createTempSync('basa_table_export_').path);
    t = wireTutor(ctx, wireShared(ctx));
    await ctx.localDb.insert('schools', {'id': 1, 'school_id': 'ZZTX1', 'school_name': 'ZZ School', 'region_id': 13});
  });

  setUp(() => signInAs('coordinator', schoolId: 1));

  XlsxWorkbook book(List<int> bytes) => XlsxWorkbook.decode(bytes);

  test('footer', () async {
    final vm = t.tableExportVm;
    expect(vm.footer(now: _now), _footer);
    expect(vm.footer(now: DateTime(2026, 11, 28, 21, 5)), 'Generated by Maria Santos (Coordinator) on 28 Nov 2026, 9:05 PM');
    expect(vm.footer(now: DateTime(2026, 11, 28, 0, 30)), 'Generated by Maria Santos (Coordinator) on 28 Nov 2026, 12:30 AM');
    await signInAs('admin');
    expect(vm.footer(now: _now), 'Generated by Maria Santos (Admin, region) on 28 Nov 2026, 9:14 AM');
    await signInAs('tutor', schoolId: 1, name: 'Noel Gica');
    expect(vm.footer(now: _now), 'Generated by Noel Gica (Tutor) on 28 Nov 2026, 9:14 AM');
  });

  test('xlsx layout', () async {
    final b = book(await t.tableExportVm.xlsx(_table, now: _now));
    const s = 'Section roster';
    expect(b.hasSheet(s), isTrue);
    expect(b.read(s, 'A1'), 'BASA - Section roster');
    expect(b.read(s, 'A2'), 'ZZ School, school year 2026-2027');
    expect(b.read(s, 'A3'), 'Grade 7, Rizal');
    expect(b.read(s, 'A4'), 'Search: cruz');
    expect(b.read(s, 'A5'), isNull);
    expect([b.read(s, 'A6'), b.read(s, 'B6'), b.read(s, 'C6')], ['LRN', 'Name', 'Score']);
    expect(b.read(s, 'A7'), '012345678901');
    expect(b.read(s, 'C7'), 8);
    expect(b.read(s, 'C8'), isNull);
    expect(b.read(s, 'A9'), isNull);
    expect(b.read(s, 'A10'), _footer);
  });

  test('print footer', () async {
    final zip = ZipDecoder().decodeBytes(await t.tableExportVm.xlsx(_table, now: _now));
    final sheet = utf8.decode(zip.findFile('xl/worksheets/sheet1.xml')!.content as List<int>);
    expect(sheet, contains('<oddFooter>&amp;L$_footer&amp;RPage &amp;P of &amp;N</oddFooter>'));
  });

  test('title with forbidden characters', () async {
    const table = ExportTable('Grade 7/8: Rizal [A]', columns: [ExportColumn('Name')]);
    final b = book(await t.tableExportVm.xlsx(table, now: _now));
    expect(b.hasSheet('Grade 78 Rizal A'), isTrue);
    expect(t.tableExportVm.fileName(table, 'xlsx', now: DateTime(2026, 11, 28)), 'Grade 7-8- Rizal [A] 2026-11-28.xlsx');
    final long = ExportTable('A' * 40, columns: const [ExportColumn('Name')]);
    expect(book(await t.tableExportVm.xlsx(long, now: _now)).hasSheet('A' * 31), isTrue);
  });

  test('row lengths', () async {
    const tooLong = ExportTable('X', columns: [ExportColumn('a'), ExportColumn('b'), ExportColumn('c')], rows: [
      [1, 2, 3, 4]
    ]);
    await expectLater(t.tableExportVm.xlsx(tooLong, now: _now),
        throwsA(isA<ViewModelException>().having((e) => e.message, 'message', 'A row has more values than the table has columns.')));
    const short = ExportTable('X', columns: [ExportColumn('a'), ExportColumn('b'), ExportColumn('c')], rows: [
      ['only']
    ]);
    final b = book(await t.tableExportVm.xlsx(short, now: _now));
    // No school line or filters: title, empty row, header (row 3), data.
    expect(b.read('X', 'A3'), 'a');
    expect(b.read('X', 'A4'), 'only');
    expect(b.read('X', 'B4'), isNull);
  });

  test('no rows', () async {
    final b = book(await t.tableExportVm.xlsx(
        const ExportTable('Section roster', school: 'ZZ School', schoolYear: '2026-2027', filters: ['Grade 7, Rizal', 'Search: cruz'],
            columns: [ExportColumn('LRN')]),
        now: _now));
    expect(b.read('Section roster', 'A6'), 'LRN');
    expect(b.read('Section roster', 'A7'), 'No rows');
  });

  test('signed out', () async {
    await ctx.authVm.signOut();
    await expectLater(t.tableExportVm.xlsx(_table, now: _now),
        throwsA(isA<ViewModelException>().having((e) => e.message, 'message', notSignedInMessage)));
  });
}
